import { SystemSection } from "@/components/journey/SystemSection";
import { AUTHORIZED, CHAPTER_COPY, stopFrame } from "@/components/journey/story";
import "@/components/journey/journey.css";
// Stand-in (README → Decisions): CC0 photograph from Wikimedia Commons, Emaar signs and an advert retouched out.
import heroPhoto from "@/components/journey/hero-dubai.jpg";

const timeline = TimelineSchema.parse(rawTimeline);
const anchors = rawAnchors as unknown as Record<string, AnchorPoint[]>; // generated by Blender (journey.anchors), shape fixed there

export async function generateMetadata(): Promise<Metadata> {
  return {
    title: "One building, every door",
    description:
      "Walk through a building fitted by AIMS: parking barriers, security gates, face recognition attendance and BioTime software.",
    alternates: alternates(await getLocale(), "/"),
  };
}

/**
 * The homepage on this branch (user, 26 Nov: "keep it in a separate branch with this as the homepage"): a visitor's
 * walk through one building, one gesture per stop; at each product a card with its catalogue facts and links. Then
 * the system they walked through, the proof and the people. Plan docs/superpowers/plans/2026-11-25-3d-homepage.md.
 */
export default async function Home() {
  const t = await getDictionary();
  const locale = await getLocale();
  const at = (path: string) => localePath(locale, path);
  const paths = {
    product: (s: string) => at(`/product/${s}`),
    software: (s: string) => at(`/software/${s}`),
    family: (s: string) => at(`/products/${s}`),
    services: at("/services"),
  };
  const beats = timeline.beats.map((b) => beatData(b, anchors, paths)).filter((b): b is BeatData => b !== null);
  const chapter = (key: string) => timeline.chapters.find((c) => c.key === key) ?? { from: 1, to: timeline.frames };
  const hero = chapter("hero");
  // Arrival, then each product's held close-up; the next gesture after the last product leaves for "Your system".
  const stops = [1, ...beats.map((b) => stopFrame(b.key, b.from, b.to))];
  // Where each checkpoint's product sits on the film, for phones (the arrival: the tower, a little left of centre).
  const nearest = (track: AnchorPoint[], f: number) =>
    track.reduce<AnchorPoint | undefined>((m, p) => (!m || Math.abs(p[0] - f) < Math.abs(m[0] - f) ? p : m), undefined);
  const focus: [number, number][] = [
    [0.45, 0.45],
    ...beats.map((b): [number, number] => {
      const p = nearest(b.track, stopFrame(b.key, b.from, b.to));
      return p ? [p[1], Math.min(p[2], 0.55)] : [0.5, 0.5]; // a low product (the barrier's lit face) shows its top half
    }),
  ];
  const firstOfChapter = new Set(timeline.chapters.map((c) => beats.find((b) => b.chapter === c.key)?.key));
  const railChapters = timeline.chapters
    .filter((c) => CHAPTER_COPY[c.key])
    .map((c) => {
      const first = beats.find((b) => b.chapter === c.key);
      return {
        key: c.key,
        label: CHAPTER_COPY[c.key]?.title ?? c.key,
        from: c.from,
        to: c.to,
        jump: first ? stopFrame(first.key, first.from, first.to) : c.from,
      };
    });

  return (
    <main id="main" className="journey-page">
      {/* Factual Organization data, as on main's homepage (Plan AT-12). */}
      <JsonLd
        data={{
          "@context": "https://schema.org",
          "@type": "Organization",
          name: COMPANY_NAME,
          url: SITE_URL,
          email: CONTACT.email,
          telephone: CONTACT.lines.headOffice.tel,
        }}
      />
      <JourneyHeader
        authorized={AUTHORIZED}
        paths={{ home: at("/"), products: at("/products"), services: paths.services, quote: at("/quote") }}
      />
      <JourneyPlayer
        timeline={timeline}
        frameSrc="/journey/frames/"
        filmAspect={1.6}
        stops={stops}
        pace={pace}
        focus={focus}
      >
        {/* The first screen is a real street (user, 27 Nov: the rendered city read as a simulation); it dissolves
            into the film as the walk begins. */}
        <Scrubbed
          from={hero.from}
          to={hero.to}
          fadeIn={[-1, -0.5]}
          fadeOut={[0.3, 0.75]}
          rise={0}
          className="hero-photo"
        >
          <Image
            src={heroPhoto}
            alt="Office towers and the motorway along Sheikh Zayed Road in Dubai at night"
            fill
            preload
            fetchPriority="high"
            // It covers the screen: on a tall phone the 3:2 photo is as wide as 1.5 screen heights.
            sizes="max(100vw, 150svh)"
            className="hero-photo-img"
          />
        </Scrubbed>
        <Scrubbed
          from={hero.from}
          to={hero.to}
          fadeIn={[-1, -0.5]}
          fadeOut={[0.3, 0.6]}
          stretch={[110, 125]}
          className="hero"
        >
          <p className="hero-badge">{AUTHORIZED}</p>
          <h1 className="hero-title">Every door of your building.</h1>
          <p className="hero-lead">{t.home.hero.lead}</p>
          <p className="hero-actions">
            <a href="#your-system" className="hero-skip">
              See the whole system
            </a>
            <Link href={at("/products")} className="hero-link">
              All products →
            </Link>
          </p>
        </Scrubbed>
        <LiftCounter from={timeline.lift.from} to={timeline.lift.to} floor={timeline.lift.floor} />
        {beats.map((b, i) => (
          <BeatCard
            key={b.key}
            beat={b}
            stopIndex={i + 1}
            chapterTitle={CHAPTER_COPY[b.chapter]?.title ?? ""}
            chapterLine={firstOfChapter.has(b.key) ? CHAPTER_COPY[b.chapter]?.line : undefined}
          />
        ))}
        <ChapterRail chapters={railChapters} />
      </JourneyPlayer>
      <SystemSection
        beats={beats}
        authorized={AUTHORIZED}
        figureLabels={{
          years: t.home.proof.years,
          installations: t.home.proof.installations,
          clients: t.home.proof.clients,
          countries: t.home.proof.countries,
        }}
        figureNote={t.home.proof.body}
        paths={{ quote: at("/quote"), services: paths.services, product: paths.product, software: paths.software }}
      />
      <p className="photo-credit">
        Street photograph: Dubai Marina and Sheikh Zayed Road at night, CC0, via{" "}
        <a
          href="https://commons.wikimedia.org/wiki/File:Dubai_Marina_and_Sheikh_Zayed_Road_from_Saba_3_JLT_at_night.jpg"
          target="_blank"
          rel="noreferrer"
        >
          Wikimedia Commons
        </a>
        .
      </p>
    </main>
  );
}
